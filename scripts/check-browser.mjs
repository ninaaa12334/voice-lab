await page.addInitScript(() => {
  Math.random = () => 0;
  navigator.mediaDevices.getUserMedia = async () => {
    const context = new AudioContext();
    const oscillator = context.createOscillator();
    const gain = context.createGain();
    const destination = context.createMediaStreamDestination();
    oscillator.frequency.value = 220; gain.gain.value = 0.3;
    window.__setMic = (frequency, amplitude) => { oscillator.frequency.setValueAtTime(frequency, context.currentTime); gain.gain.setValueAtTime(amplitude, context.currentTime); };
    oscillator.connect(gain).connect(destination);
    await context.resume(); oscillator.start();
    window.__micStopped = false;
    const track = destination.stream.getAudioTracks()[0];
    const stop = track.stop.bind(track);
    track.stop = () => { window.__micStopped = true; oscillator.stop(); void context.close(); stop(); };
    return destination.stream;
  };
});
